from pyspark.sql import DataFrame
from pyspark.sql import functions as F
from pyspark.sql.window import Window

def transform_gold_features_and_rul(
    df: DataFrame, 
    max_rul_cap: int = 125, 
    is_test_set: bool = False, 
    rul_ground_truth_df: DataFrame = None
) -> DataFrame:
    """
    Computes RUL target label, Min-Max normalization, trend velocity, 
    and strict backward-looking rolling features for C-MAPSS.
    """
    # 1. Standardize schema
    df_standardized = df
    if "unit_id" in df_standardized.columns:
        df_standardized = df_standardized.withColumnRenamed("unit_id", "engine_id")
    if "time_cycle" in df_standardized.columns:
        df_standardized = df_standardized.withColumnRenamed("time_cycle", "cycle")

    # Define windows
    w_engine = Window.partitionBy("engine_id")
    w_rolling_5 = Window.partitionBy("engine_id").orderBy("cycle").rowsBetween(-4, 0)
    w_rolling_15 = Window.partitionBy("engine_id").orderBy("cycle").rowsBetween(-14, 0)

    # 2. Handle RUL based on dataset split type
    if not is_test_set:
        df_with_max = df_standardized.withColumn(
            "max_cycle", F.max("cycle").over(w_engine)
        )
        df_with_rul = df_with_max.withColumn(
            "raw_rul", F.col("max_cycle") - F.col("cycle")
        )
    else:
        if rul_ground_truth_df is None:
            raise ValueError("rul_ground_truth_df must be provided when processing test datasets.")
        
        df_test_max = df_standardized.groupBy("engine_id").agg(F.max("cycle").alias("last_recorded_cycle"))
        df_gt_total = rul_ground_truth_df.withColumnRenamed("rul", "true_remaining_rul")
        df_engine_total_life = df_test_max.join(df_gt_total, "engine_id").withColumn(
            "max_cycle", F.col("last_recorded_cycle") + F.col("true_remaining_rul")
        )
        
        df_with_rul_prep = df_standardized.join(df_engine_total_life, "engine_id")
        df_with_rul = df_with_rul_prep.withColumn(
            "raw_rul", F.col("max_cycle") - F.col("cycle")
        )

    # 3. Apply Piecewise RUL Cap (capped at 125 cycles)
    cols_to_drop = [c for c in ["raw_rul", "last_recorded_cycle", "true_remaining_rul", "error"] if c in df_with_rul.columns]
    df_capped_rul = df_with_rul.withColumn(
        "rul",
        F.when(F.col("raw_rul") > max_rul_cap, max_rul_cap).otherwise(F.col("raw_rul"))
    ).drop(*cols_to_drop)

    # 4. Critical Sensor Feature Engineering Overhaul
    critical_sensors = ["sensor_2", "sensor_3", "sensor_4", "sensor_11", "sensor_12", "sensor_15"]
    if not any(c in df_capped_rul.columns for c in critical_sensors):
        critical_sensors = ["s_2", "s_3", "s_4", "s_11", "s_12", "s_15"]

    df_features = df_capped_rul
    for sensor in critical_sensors:
        if sensor in df_features.columns:
            # A. Min-Max Normalization per engine (bounds sensor values between 0.0 and 1.0)
            min_col = F.min(sensor).over(w_engine)
            max_col = F.max(sensor).over(w_engine)
            df_features = df_features.withColumn(
                f"{sensor}_norm",
                (F.col(sensor) - min_col) / (F.when((max_col - min_col) == 0, 1.0).otherwise(max_col - min_col))
            )

            # B. Short-term rolling statistics (5 cycles)
            df_features = df_features.withColumn(f"{sensor}_roll_mean_5", F.avg(F.col(sensor)).over(w_rolling_5))
            df_features = df_features.withColumn(f"{sensor}_roll_std_5", F.stddev(F.col(sensor)).over(w_rolling_5))
            
            # C. Trend / Velocity vector (Divergence from short-term mean)
            df_features = df_features.withColumn(f"{sensor}_trend_5", F.col(sensor) - F.col(f"{sensor}_roll_mean_5"))

            # D. Medium-term smoothing (15 cycles) to capture broader degradation slope
            df_features = df_features.withColumn(f"{sensor}_roll_mean_15", F.avg(F.col(sensor)).over(w_rolling_15))

    # Fill any nulls generated by early rolling windows with 0
    return df_features.na.fill(0)


def build_fact_engine_telemetry(featured_df: DataFrame) -> DataFrame:
  """Selects all base sensors, normalized features, trends, and rolling metrics for the Gold fact table."""
  all_cols = featured_df.cols if hasattr(featured_df, "cols") else featured_df.columns
  
  sensor_cols = [
      c for c in all_cols 
      if (c.startswith("sensor_") or c.startswith("s_")) and "_roll_" not in c and "_norm" not in c and "_trend_" not in c
  ]
  setting_cols = [c for c in all_cols if c.startswith("setting_")]
  
  # Automatically capture all engineered feature columns
  engineered_cols = [c for c in all_cols if "_roll_" in c or "_norm" in c or "_trend_" in c]

  return featured_df.select(
      "engine_id",
      "cycle",
      *setting_cols,
      *sensor_cols,
      *engineered_cols,
      "rul",
      "max_cycle",
      "ingest_timestamp",
  )


def build_dim_engine(featured_df: DataFrame) -> DataFrame:
  """Builds the engine dimension table."""
  return (
      featured_df.groupBy("engine_id")
      .agg(
          F.max("max_cycle").alias("total_lifespan_cycles"),
          F.min("cycle").alias("first_recorded_cycle"),
      )
      .withColumn(
          "health_status_category",
          F.when(
              F.col("total_lifespan_cycles") < 150, "Early Failure"
          ).otherwise("Standard Wear"),
      )
  )